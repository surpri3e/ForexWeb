export const SKILL_IDS = Object.keys(SKILLS);
export const skillName = (id) => (SKILLS[id] ? SKILLS[id].icon + ' ' + SKILLS[id].name : id);

// تشخیص اسکیل‌های مرتبط با پیام (حداکثر ۲ تا؛ اسکیل‌های خاموش‌شده توسط ادمین حذف می‌شن)
export function detectSkills(text, ctx = {}, off = []) {
  const t = String(text || '');
  const hit = [];
  for (const id of SKILL_IDS) {
    if (off && off.includes(id)) continue;
    const s = SKILLS[id];
    try { if (s.test(t, ctx)) hit.push(id); } catch (e) { /* ignore */ }
  }
  // فایل: همیشه اولویت با تحلیل فایل؛ بقیه به ترتیب اولویت
  hit.sort((a, b) => SKILLS[a].pri - SKILLS[b].pri);
  // اگه عکس فرستاده شده و چارت تنها دلیل فعال شدنه، با اسکیل‌های «متنی» قاطی نمی‌شه مگر صراحتاً خواسته شده باشه
  return hit.slice(0, 2);
}
// برنامهٔ اجرا از روی اسکیل‌های فعال
export function planFor(ids) {
  const plan = { ids: ids || [], sys: '', search: '', think: '', tier: '', maxTokens: 0, limit: 0, review: false, calc: false, long: false, needsJournal: false };
  for (const id of plan.ids) {
    const s = SKILLS[id]; if (!s) continue;
    plan.sys += '\n\n--- مهارت فعال: ' + s.name + ' ---\n' + s.sys;
    if (s.search === 'always') plan.search = 'always';
    if (s.think && (!plan.think || TH[s.think] > TH[plan.think])) plan.think = s.think;
    if (s.tier === 'strong') plan.tier = 'strong';
    plan.maxTokens = Math.max(plan.maxTokens, s.maxTokens || 0);
    plan.limit = Math.max(plan.limit, s.limit || 0);
    plan.review = plan.review || !!s.review; plan.calc = plan.calc || !!s.calc; plan.long = plan.long || !!s.long; plan.needsJournal = plan.needsJournal || !!s.needsJournal;
  }
  return plan;
}
