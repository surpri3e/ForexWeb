// صفحه‌های یک ماه: هر روزِ دارای مناسبت یک بلوک، با تاریخ هر سه تقویم و توضیح هر مناسبت؛ حداکثر حدود ۳۴۰۰ نویسه در هر صفحه
function monthPages(kind, y, m, today) {
  let head, days = [];
  if (kind === 's') {
    const n = jMonthDays(y, m); head = '<b>📅 تقویم ' + J_MONTHS[m - 1] + ' ' + faNum(y) + '</b>\n<i>شمسی، قمری و جهانی؛ هر روز با تاریخ هر سه تقویم</i>\n';
    for (let d = 1; d <= n; d++) { const g = toGregorian(y, m, d); days.push(dayData(g.gy, g.gm, g.gd)); }
  } else {
    const n = new Date(Date.UTC(y, m, 0)).getUTCDate(); const j1 = toJalali(y, m, 1);
    head = '<b>🌍 تقویم میلادی ' + G_MONTHS[m - 1] + ' ' + faNum(y) + '</b>\n<i>معادل ' + J_MONTHS[j1.jm - 1] + ' ' + faNum(j1.jy) + '؛ هر روز با تاریخ هر سه تقویم</i>\n';
    for (let d = 1; d <= n; d++) days.push(dayData(y, m, d));
  }
  const blocks = [];
  for (const dd of days) {
    const all = dd.solar.map((i) => Object.assign({ s: 's' }, i)).concat(dd.lunar.map((i) => Object.assign({ s: 'l' }, i)), dd.global.map((i) => Object.assign({ s: 'g' }, i)));
    if (!all.length) continue;
    const isToday = today && today.y === dd.g.gy && today.m === dd.g.gm && today.d === dd.g.gd;
    let b = '\n<b>' + faNum(kind === 's' ? dd.j.jd : dd.g.gd) + ' ' + (kind === 's' ? J_MONTHS[dd.j.jm - 1] : G_MONTHS[dd.g.gm - 1]) + '</b> · ' + WD_FA[dd.wd] + (dd.holiday ? ' · 🔴 تعطیل' : '') + (isToday ? ' · ◀️ امروز' : '') + '\n' +
      '<i>' + faNum(dd.g.gd) + ' ' + G_MONTHS[dd.g.gm - 1] + ' · ' + faNum(dd.j.jd) + ' ' + J_MONTHS[dd.j.jm - 1] + ' · ' + faNum(dd.h.d) + ' ' + HIJRI_M[dd.h.m - 1] + '</i>\n';
    for (const i of all) b += evLine(i, '   ', SRC_FA[i.s]);
    blocks.push(b);
  }
  const pages = []; let cur = '';
  for (const b of blocks) { if (cur && (head.length + cur.length + b.length) > 3400) { pages.push(cur); cur = ''; } cur += b; }
  if (cur || !pages.length) pages.push(cur || '\nمناسبت یا تعطیلی ثبت‌شده‌ای نیست.\n');
  return { head, pages };
}
