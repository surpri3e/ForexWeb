export function persianMonth(jy, jm) {
  const n = jMonthDays(jy, jm), days = [];
  for (let d = 1; d <= n; d++) days.push({ d, wd: jWeekday(jy, jm, d), items: [], holiday: false, approx: false });
  for (const [m, d, t, h] of SOLAR) if (m === jm && d <= n) { const x = days[d - 1]; x.items.push({ t, h: !!h, src: 's' }); if (h) x.holiday = true; }
  for (const e of lunarOf(jy)) if (e.m === jm && e.d <= n) { const x = days[e.d - 1]; if (!x.items.some((i) => i.t === e.t)) x.items.push({ t: e.t, h: true, approx: e.approx, src: 'l' }); x.holiday = true; if (e.approx) x.approx = true; }
  // تاریخ قمری هر روز + مناسبت‌های قمری غیرتعطیل (تقریبی؛ رؤیت هلال در ایران ممکنه یک روز فرق داشته باشه)
  for (const x of days) {
    const g = toGregorian(jy, jm, x.d), hh = hijriOf(g.gy, g.gm, g.gd); x.hj = hh; x.g = g;
    for (const [lm, ld, t] of HIJRI_EV) if (hh.m === lm && hh.d === ld && !x.items.some((i) => i.t === t)) x.items.push({ t, h: false, approx: true, src: 'l' });
  }
  // «عید فطر» و «نوروز» توی یک روز هم‌پوشانی دارن؛ تعطیلات نوروز با عنوان تکراری یکی بشه
  for (const x of days) { const seen = new Set(); x.items = x.items.filter((i) => (seen.has(i.t) ? false : (seen.add(i.t), true))); }
  return { jy, jm, name: J_MONTHS[jm - 1], days, firstWd: days[0].wd, verified: !!VERIFIED[jy], holidays: days.filter((x) => x.holiday).length };
}
